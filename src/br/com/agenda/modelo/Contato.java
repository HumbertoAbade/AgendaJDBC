package br.com.agenda.modelo;

// API JDBC > Java Database Conectivity

import java.util.Objects;

public class Contato {
    //JAVABEAN
    //ATRIBUTOS PRIVADOS
    private int id;
    private String nome;
    private String telefone; //para não apagar o zero, é feito como texto
    private String email;

    //CONSTRUTOR PADRÃO E UM CHEIO

    public Contato() {
    }

    public Contato(int id, String nome, String telefone, String email) {
        this.id = id;
        this.nome = nome;
        this.telefone = telefone;
        this.email = email;
    }

    // GETTER E SETTER

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getTelefone() {
        return telefone;
    }

    public void setTelefone(String telefone) {
        this.telefone = telefone;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    // toString

    @Override
    public String toString() {
        return "Contato{" +
                "id=" + id +
                ", nome='" + nome + '\'' +
                ", telefone='" + telefone + '\'' +
                ", email='" + email + '\'' +
                '}';
    }

}
